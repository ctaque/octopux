    // The application state, declared (or re-exported) at the root of the crate
    use crate::AppState;
    use crate::customer::{Customer, Id};
    use crate::project::Project;
    use serde::Deserialize;
    use octopux::{
        HasMany,
        anyhow::Result,
        async_trait,
    };
    use apistos::ApiComponent;
    use schemars::JsonSchema;
    use octopux::gen_documented_relation_endpoint;

    #[derive(Deserialize, JsonSchema, ApiComponent)]
    pub struct CustomerProjectsQuery {
        /// Number of rows to skip
        pub offset: Option<usize>,
        /// Maximum number of rows to return (20 by default, 100 at most)
        pub limit: Option<usize>,
    }
    /// Number of children returned when no limit is given
    const DEFAULT_LIMIT: i64 = 20;
    /// Maximum number of children returned
    const MAX_LIMIT: i64 = 100;

    /// The projects of a customer, served on `GET /customer/{id}/projects`
    pub struct CustomerProjects;

    #[async_trait]
    impl HasMany for CustomerProjects {
        type Parent = Customer;
        type Id = Id;
        type Query = CustomerProjectsQuery;
        type Result = Vec<Project>;
        type State = AppState;
        const RELATION: &'static str = "projects";

        async fn list_related(id: Id, query: &CustomerProjectsQuery, state: &AppState) -> Result<Option<Vec<Project>>> {
            let offset = query.offset.unwrap_or(0) as i64;
            let limit = query.limit.map_or(DEFAULT_LIMIT, |l| (l as i64).min(MAX_LIMIT));
            let models = sqlx::query_as::<_, Project>(
                "SELECT * FROM project WHERE customer_id = $1 ORDER BY id LIMIT $2 OFFSET $3",
            )
            .bind(id)
            .bind(limit)
            .bind(offset)
            .fetch_all(&state.pool)
            .await?;
            // the parent is only looked up when the page is empty
            if models.is_empty() {
                let parent = sqlx::query_scalar::<_, Id>(
                    "SELECT id FROM customer WHERE id = $1",
                )
                .bind(id)
                .fetch_optional(&state.pool)
                .await?;
                if parent.is_none() {
                    return Ok(None);
                }
            }
            Ok(Some(models))
        }
    }

    // Registers the route of the projects of a customer, to mount with `.configure(customer_projects::configure)`
    // in the same scope as the customer routes
    pub fn configure(cfg: &mut apistos::web::ServiceConfig) {
        gen_documented_relation_endpoint!(CustomerProjects)(cfg)
    }

    // Resolves the `projects` field of the GraphQL Customer type, declared in the `#[ComplexObject]` of its model
    pub async fn resolve(ctx: &async_graphql::Context<'_>, id: Id, offset: Option<usize>, limit: Option<usize>) -> async_graphql::Result<Vec<Project>> {
        let state = ctx.data::<actix_web::web::Data<AppState>>()?;
        let children = CustomerProjects::list_related(id, &CustomerProjectsQuery { offset, limit }, state.get_ref()).await?;
        // the parent was resolved, so it exists
        Ok(children.unwrap_or_default())
    }
    